"""Builds the HR question bank: src/lib/demo/hr-questions.ts and public/hr-question-bank.pdf.

Run from apps/web:  python3 scripts/build-hr-question-bank.py
"""
import json
from pathlib import Path

from reportlab.lib.colors import HexColor
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle
from reportlab.lib.units import mm
from reportlab.platypus import KeepTogether, ListFlowable, ListItem, Paragraph, SimpleDocTemplate, Spacer

BANK = [
    ("Hiring interviews", "Behaviour-based questions. Ask for a specific example, then follow up on what they did and what happened.", [
        "Tell me about a time you had to learn something new quickly to get a job done.",
        "Describe a disagreement with a colleague. How did you handle it, and what was the outcome?",
        "Walk me through a project you're proud of. What was your part in it?",
        "Tell me about a mistake you made at work. What did you do next?",
        "Describe a time you had several urgent tasks at once. How did you decide what to do first?",
        "Give an example of feedback that changed how you work.",
        "Tell me about a time you helped a customer or colleague who was unhappy.",
        "What kind of manager helps you do your best work?",
    ]),
    ("Onboarding check-ins (30, 60, 90 days)", "Short conversations to catch problems early in a new joiner's first months.", [
        "What has surprised you most since you joined?",
        "Do you have everything you need to do your job: tools, access, information?",
        "Who has been most helpful so far? Is there anyone you haven't met yet but should?",
        "Is your role what you expected when you accepted the offer? What's different?",
        "What is one thing we could do to make onboarding better for the next person?",
        "How confident do you feel about your goals for the next 3 months, from 1 to 10?",
    ]),
    ("One-on-ones", "For managers. Rotate a few of these into regular one-on-ones.", [
        "What's going well for you right now?",
        "What's getting in your way, and how can I help?",
        "Is there anything you'd like more or less of from me?",
        "Which part of your work gives you the most energy? The least?",
        "What would you like to learn or try in the next 6 months?",
        "Is there anything happening in the team I should know about?",
        "How is your workload this month: too light, about right, or too much?",
    ]),
    ("Engagement pulse survey", "Ask on a 1 to 5 agree scale, every month or quarter. Track the trend, not single scores.", [
        "I know what is expected of me at work.",
        "I have the tools and information I need to do my job well.",
        "In the last month, someone recognised me for good work.",
        "My manager cares about me as a person.",
        "I can see how my work contributes to the company's goals.",
        "I would recommend this company as a place to work.",
        "I see myself still working here in two years.",
    ]),
    ("Performance reviews", "Use with the employee's self-review. Focus on examples and next steps.", [
        "Which goals did you meet this period? Which did you miss, and why?",
        "What are you most proud of from this period?",
        "Which skills have you grown most? Which do you want to grow next?",
        "What support would help you reach your goals next period?",
        "How well do you feel your work was recognised this period?",
        "What should we start, stop and continue doing as a team?",
    ]),
    ("Psychometric follow-up", "To discuss results someone has chosen to share. Never use scores to rank people.", [
        "Which of your results felt most true? Which surprised you?",
        "When do you do your best work, and what conditions help?",
        "How do you like to receive feedback?",
        "Which teammate's working style is most different from yours? How do you work well together?",
        "Is there a trait you'd like to develop? What would a small first step look like?",
    ]),
    ("Exit interviews", "Keep it confidential and listen more than you talk.", [
        "What made you start looking for a new role?",
        "What could we have done to keep you?",
        "What did you enjoy most about working here?",
        "How would you describe the support you got from your manager?",
        "Was your work recognised fairly? What could be better?",
        "Would you consider coming back in the future? What would need to change?",
    ]),
]

root = Path(__file__).resolve().parents[1]

# 1. Data for the HR toolkit page.
ts = "/** Generated by scripts/build-hr-question-bank.py. Edit the script, not this file. */\n"
ts += "export const HR_QUESTION_BANK: { title: string; note: string; questions: string[] }[] = "
ts += json.dumps([{"title": t, "note": n, "questions": q} for t, n, q in BANK], indent=2, ensure_ascii=False) + ";\n"
(root / "src/lib/demo/hr-questions.ts").write_text(ts, encoding="utf-8")

# 2. The printable PDF.
ink, muted, brand = HexColor("#0f172a"), HexColor("#475569"), HexColor("#4f46e5")
title = ParagraphStyle("t", fontName="Helvetica-Bold", fontSize=22, leading=28, textColor=ink)
sub = ParagraphStyle("s", fontName="Helvetica", fontSize=11, leading=16, textColor=muted)
h2 = ParagraphStyle("h2", fontName="Helvetica-Bold", fontSize=14, leading=19, textColor=brand, spaceBefore=14, spaceAfter=2)
note = ParagraphStyle("n", fontName="Helvetica-Oblique", fontSize=10, leading=14, textColor=muted, spaceAfter=6)
q = ParagraphStyle("q", fontName="Helvetica", fontSize=11, leading=16, textColor=ink)

story = [
    Paragraph("HR question bank", title),
    Paragraph("Ready-to-use questions for interviews, onboarding, one-on-ones, surveys, reviews and exits. From the Engage HR toolkit.", sub),
    Spacer(1, 6 * mm),
]
for t, n, qs in BANK:
    items = ListFlowable([ListItem(Paragraph(x, q), leftIndent=14) for x in qs], bulletType="1", bulletFontSize=10, bulletColor=muted, leftIndent=16)
    story.append(KeepTogether([Paragraph(t, h2), Paragraph(n, note), items]))


def footer(canvas, doc):
    canvas.saveState()
    canvas.setFont("Helvetica", 8.5)
    canvas.setFillColor(muted)
    canvas.drawString(18 * mm, 10 * mm, "Engage HR toolkit")
    canvas.drawRightString(A4[0] - 18 * mm, 10 * mm, f"Page {doc.page}")
    canvas.restoreState()


out = root / "public/hr-question-bank.pdf"
SimpleDocTemplate(str(out), pagesize=A4, leftMargin=18 * mm, rightMargin=18 * mm, topMargin=18 * mm, bottomMargin=18 * mm,
                  title="HR question bank", author="Engage").build(story, onFirstPage=footer, onLaterPages=footer)
print("wrote", out, out.stat().st_size, "bytes and hr-questions.ts")
